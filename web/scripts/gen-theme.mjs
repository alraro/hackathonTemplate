// Generates every visual-token output from src/design/theme.json (run: make theme / npm run theme).
// Outputs: src/design/generated/{theme.css,motion.ts}, ../mobile/theme.ts (if mobile/), ../pitch/theme.css (if pitch/).
import fs from "node:fs"
import path from "node:path"
import { formatHex8, parse } from "culori"

const root = path.resolve(import.meta.dirname, "..")
const repo = path.resolve(root, "..")
const theme = JSON.parse(fs.readFileSync(path.join(root, "src/design/theme.json"), "utf8"))
const schema = JSON.parse(fs.readFileSync(path.join(root, "src/design/preset.schema.json"), "utf8"))

const check = (cond, msg) => {
  if (!cond) {
    console.error(`theme.json: ${msg}`)
    process.exit(1)
  }
}
for (const k of schema.required) check(k in theme, `missing "${k}"`)
for (const [mode, pal] of Object.entries(theme.colors)) {
  for (const k of schema.$defs.palette.required) check(k in pal, `colors.${mode}.${k} missing`)
  for (const [k, v] of Object.entries(pal)) check(parse(v)?.mode === "oklch", `colors.${mode}.${k} is not valid oklch: ${v}`)
}

const NOTE = "GENERATED by web/scripts/gen-theme.mjs from web/src/design/theme.json. DO NOT EDIT - run `make theme`."
const cssHeader = `/* ${NOTE} */`
const tsHeader = `// ${NOTE}`
const write = (file, content) => {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content)
  console.log(`theme: wrote ${path.relative(repo, file)}`)
}

const vars = (obj) => Object.entries(obj).map(([k, v]) => `  --${k}: ${v};`).join("\n")
const bezier = (e) => `cubic-bezier(${e.join(", ")})`
const fontStack = (f, fallback) => `"${f.family}", ${fallback}`
const { motion, fonts } = theme
const semantic = Object.keys(theme.colors.light)
const rmDuration = theme.reducedMotion?.duration
const durations = (d, indent = "  ") => Object.entries(d).map(([k, v]) => `${indent}--duration-${k}: ${v}ms;`).join("\n")
const fontVars = () =>
  [
    `  --font-display-family: ${fontStack(fonts.display, "ui-sans-serif, system-ui, sans-serif")};`,
    `  --font-body-family: ${fontStack(fonts.body, "ui-sans-serif, system-ui, sans-serif")};`,
    `  --font-mono-family: ${fontStack(fonts.mono, "ui-monospace, monospace")};`,
  ].join("\n")

// --- web theme.css ---
// Self-hosted fonts (@fontsource) of the active theme; @import rules must come first.
const fontPackages = (f) => [...new Set(Object.values(f).map((x) => x.package))]
const fontImports = (pkgs) => pkgs.map((p) => `@import "${p}";`).join("\n")
const themeCss = `${cssHeader}

${fontImports(fontPackages(fonts))}

@theme inline {
${semantic.map((k) => `  --color-${k}: var(--${k});`).join("\n")}
  --radius-sm: calc(var(--radius) - 4px);
  --radius-md: calc(var(--radius) - 2px);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) + 4px);
  --font-display: var(--font-display-family);
  --font-sans: var(--font-body-family);
  --font-mono: var(--font-mono-family);
${Object.keys(theme.shadow).map((k) => `  --shadow-${k}: var(--shadow-${k}-value);`).join("\n")}
}

:root {
  --radius: ${theme.radius};
${vars(theme.colors.light)}
${fontVars()}
${Object.entries(theme.shadow).map(([k, v]) => `  --shadow-${k}-value: ${v};`).join("\n")}
${durations(motion.duration)}
${Object.entries(motion.easing).map(([k, v]) => `  --ease-${k}: ${bezier(v)};`).join("\n")}
  --focus-ring-width: ${theme.focus.width};
  --focus-ring-offset: ${theme.focus.offset};
}
${theme.colors.dark ? `\n.dark {\n${vars(theme.colors.dark)}\n}\n` : ""}${
  rmDuration ? `\n@media (prefers-reduced-motion: reduce) {\n  :root {\n${durations(rmDuration, "    ")}\n  }\n}\n` : ""
}${theme.effects.length ? `\n/* effects: ${theme.effects.join(", ")} */\n` : ""}`
write(path.join(root, "src/design/generated/theme.css"), themeCss)

// --- preset-fonts.css: fonts of every preset, loaded by /showcase so the preset switch shows each look ---
const presetDir = path.join(root, "src/design/presets")
const presetPkgs = new Set()
for (const f of fs.readdirSync(presetDir).filter((n) => n.endsWith(".json")).sort()) {
  for (const p of fontPackages(JSON.parse(fs.readFileSync(path.join(presetDir, f), "utf8")).fonts)) presetPkgs.add(p)
}
write(path.join(root, "src/design/generated/preset-fonts.css"), `${cssHeader}\n\n${fontImports([...presetPkgs])}\n`)

// --- motion.ts ---
const seconds = (d) => Object.fromEntries(Object.entries(d).map(([k, v]) => [k, v / 1000]))
const json = (v) => JSON.stringify(v, null, 2)
const motionTs = `${tsHeader}

export const duration = ${json(seconds(motion.duration))} as const // seconds (Motion)

export const easing = ${json(motion.easing)} as const // cubic-bezier control points

export const spring = { type: "spring", ...${JSON.stringify(motion.spring)} } as const

export const reducedMotion = ${json({
  duration: seconds(rmDuration ?? {}),
  spring: theme.reducedMotion?.spring ?? {},
})} as const

export const effects = ${JSON.stringify(theme.effects)} as const
`
write(path.join(root, "src/design/generated/motion.ts"), motionTs)

// --- mobile/theme.ts ---
const hex = (v) => {
  const h = formatHex8(parse(v))
  return h.endsWith("ff") ? h.slice(0, 7) : h
}
const palette = (p) => Object.fromEntries(Object.entries(p).map(([k, v]) => [k, hex(v)]))
const px = (len) => (len.endsWith("rem") ? parseFloat(len) * 16 : parseFloat(len))
if (fs.existsSync(path.join(repo, "mobile"))) {
  const mobileTs = `${tsHeader}

export const colors = ${json({
    light: palette(theme.colors.light),
    ...(theme.colors.dark ? { dark: palette(theme.colors.dark) } : {}),
  })} as const

export const radius = ${px(theme.radius)}

export const fonts = ${json(Object.fromEntries(Object.entries(fonts).map(([k, f]) => [k, f.family])))} as const

export const duration = ${json(motion.duration)} as const // milliseconds
`
  write(path.join(repo, "mobile/theme.ts"), mobileTs)
}

// --- pitch/theme.css ---
if (fs.existsSync(path.join(repo, "pitch"))) {
  const pitchCss = `${cssHeader}

:root {
  --radius: ${theme.radius};
${vars(theme.colors.light)}
${fontVars()}
${durations(motion.duration)}
}
`
  write(path.join(repo, "pitch/theme.css"), pitchCss)
}
