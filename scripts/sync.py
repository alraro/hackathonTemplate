"""Maintainer script: copy skills per agent, inject the footer, generate CATALOG.md.

    python scripts/sync.py           write generated files
    python scripts/sync.py --check   exit 1 if anything would change (CI)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _manifest import ROOT, load_features, load_modules  # noqa: E402

START = "<!-- sync:footer:start -->"
END = "<!-- sync:footer:end -->"
BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END) + r"\n?", re.S)


def inject_footer(text: str, footer: str) -> str:
    block = f"{START}\n{footer.strip()}\n{END}\n"
    text = BLOCK.sub("", text).rstrip("\n")
    return f"{text}\n\n{block}"


def _cell(s) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def generate_catalog(root: Path = ROOT) -> str:
    modules = load_modules(root)
    features = load_features(root)
    lines = [
        "# Catalog",
        "",
        "<!-- Generated by `make sync`. Do not edit. -->",
        "",
        "## Core",
        "",
        "Never pruned: `docker-compose.yml` (services by profile), `Makefile` (`make help` lists targets), `scripts/` (setup and maintainer scripts).",
        "",
        "## Modules",
        "",
        "| Module | Lane | Requires | Keep when |",
        "|---|---|---|---|",
    ]
    for m in modules:
        if m["module"] == "pitch":
            continue
        keep = _cell(m["keep_when"])
        feats = m.get("features") or []
        if feats and not any(features.get(f["id"], False) for f in feats):
            keep += " **(no Feature implemented yet: Prune may drop it)**"
        lines.append(f"| `{_cell(m['module'])}` | {_cell(m['lane'])} | {_cell(', '.join(m.get('requires') or []) or '-')} | {keep} |")
    lines.append("| `pitch` | pitch | - | never pruned |")
    lines += ["", "## Features", "", "| Feature | Module | Gives | Entry | Keep when | State |", "|---|---|---|---|---|---|"]
    for m in modules:
        for f in m.get("features") or []:
            state = "on" if features.get(f["id"], False) else "off"
            lines.append(f"| `{_cell(f['id'])}` | `{_cell(m['module'])}` | {_cell(f['gives'])} | {_cell(f['entry'])} | {_cell(f['keep_when'])} | {state} |")
    return "\n".join(lines) + "\n"


def desired_files(root: Path = ROOT) -> dict[Path, str]:
    """Map every generated or rewritten file to its expected content."""
    skills_dir = root / ".agents" / "skills"
    footer = (skills_dir / "_footer.md").read_text(encoding="utf-8")
    want: dict[Path, str] = {}
    for d in sorted(p for p in skills_dir.iterdir() if p.is_dir() and not p.name.startswith("_")):
        for src in sorted(p for p in d.rglob("*") if p.is_file()):
            rel = src.relative_to(skills_dir)
            content = src.read_text(encoding="utf-8")
            if src.name == "SKILL.md":
                content = inject_footer(content, footer)
                want[src] = content
            for t in (root / ".claude" / "skills", root / ".github" / "skills"):
                want[t / rel] = content
    want[root / "CATALOG.md"] = generate_catalog(root)
    return want


def _skill_dir(root: Path, t: Path, p: Path) -> Path:
    return t / p.relative_to(t).parts[0]


def stale_copies(root: Path, want: dict[Path, str]) -> list[Path]:
    """Template-generated files in target dirs that no longer have a canonical source.

    A skill folder counts as generated only if its SKILL.md carries the footer marker, so a
    team's hand-made skill (no marker) is never removed.
    """
    stale = []
    for t in (root / ".claude" / "skills", root / ".github" / "skills"):
        if not t.is_dir():
            continue
        generated: dict[Path, bool] = {}
        for p in t.rglob("*"):
            if not p.is_file() or p in want:
                continue
            d = _skill_dir(root, t, p)
            if d not in generated:
                md = d / "SKILL.md"
                generated[d] = md.is_file() and START in md.read_text(encoding="utf-8")
            if generated[d]:
                stale.append(p)
    return stale


def main(argv: list[str]) -> int:
    check = "--check" in argv
    want = desired_files()
    changed = [p for p, c in want.items() if not p.is_file() or p.read_text(encoding="utf-8") != c]
    stale = stale_copies(ROOT, want)
    if check:
        for p in changed + stale:
            print(f"stale: {p.relative_to(ROOT)}")
        if changed or stale:
            print("Run `make sync`.")
        return 1 if changed or stale else 0
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(want[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    for p in stale:
        p.unlink()
        print(f"removed {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
